"""
Aggregate power-grid LG-ODE experiment result JSON files.

Outputs
-------
results.csv
    One standardized row per experiment result JSON, including normalized,
    physical-unit, physics-consistency, runtime, and parameter-count metrics.

summary.csv
    Aggregated by:
        task
        observed_fraction
        model

    Reports:
        normalized MSE and MAE
        voltage-magnitude MAE in p.u.
        voltage-angle MAE in degrees
        active-power MAE in MW
        reactive-power MAE in MVAr
        active and reactive AC residuals
        voltage-violation rate
        validation statistics
        runtime
        parameter counts

paired_comparisons.csv
    Seed-paired comparisons:

        AT-ODE versus LG-ODE
        LG-ODE versus Latent ODE
        AT-ODE versus Latent ODE

    The relative MSE improvement for model A versus model B is:

        100 * (MSE_B - MSE_A) / MSE_B

    Therefore, the main AT-ODE transport improvement is:

        100 * (MSE_LGODE - MSE_ATODE) / MSE_LGODE

Notes
-----
Normalized MSE remains the primary checkpoint-selection and paired-comparison
metric. Physical-unit feature metrics and AC-consistency metrics are retained
as separate reporting metrics; they are not silently folded into the training
objective.

Physical metrics are written to the CSV outputs even if older result files do
not contain them. Missing values are represented as NaN. Use
``--require-physical-metrics`` to reject result files that do not contain all
required physical reporting metrics.

Example
-------
python scripts/summarize_powergrid_lgode.py \\
    --input-dir results/powergrid_lgode \\
    --output-dir results/powergrid_lgode/summary \\
    --require-physical-metrics
"""

