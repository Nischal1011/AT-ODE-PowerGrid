def _normalize_key(key: str) -> str:
    return (
        str(key)
        .strip()
        .lower()
        .replace("-", "_")
        .replace(" ", "_")
    )


def _flatten_mapping(
    value: Mapping[str, Any],
    prefix: str = "",
) -> Dict[str, Any]:
    """
    Flatten a nested JSON mapping using normalized dotted keys.

    Example
    -------
    {"test": {"physical_metrics": {"voltage_magnitude_mae_pu": 0.01}}}

    becomes:

    {"test.physical_metrics.voltage_magnitude_mae_pu": 0.01}
    """

    flattened: Dict[str, Any] = {}

    for raw_key, item in value.items():
        key = _normalize_key(raw_key)
        full_key = f"{prefix}.{key}" if prefix else key

        if isinstance(item, Mapping):
            flattened.update(
                _flatten_mapping(item, prefix=full_key)
            )
        else:
            flattened[full_key] = item

    return flattened


def _candidate_value(
    flattened: Mapping[str, Any],
    candidates: Sequence[str],
    *,
    default: Any = None,
    required: bool = False,
    field_name: Optional[str] = None,
) -> Any:
    """Return the first non-null value matching a candidate key."""

    normalized_candidates = [
        ".".join(
            _normalize_key(part)
            for part in candidate.split(".")
        )
        for candidate in candidates
    ]

    for candidate in normalized_candidates:
        if (
            candidate in flattened
            and flattened[candidate] is not None
        ):
            return flattened[candidate]

    # Support result wrappers such as
    # "results.test.physical_metrics.voltage_magnitude_mae_pu".
    for candidate in normalized_candidates:
        suffix = f".{candidate}"
        matches = [
            value
            for key, value in flattened.items()
            if key.endswith(suffix) and value is not None
        ]

        if len(matches) == 1:
            return matches[0]

    if required:
        label = field_name or "/".join(candidates)
        raise KeyError(f"Missing required result field: {label}")

    return default


def _to_float(
    value: Any,
    field_name: str,
    *,
    finite: bool = True,
) -> float:
    if isinstance(value, bool):
        raise ValueError(
            f"{field_name} must be numeric, not boolean"
        )

    try:
        result = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"{field_name} must be numeric; got {value!r}"
        ) from exc

    if finite and not math.isfinite(result):
        raise ValueError(
            f"{field_name} must be finite; got {result}"
        )

    return result


def _optional_float(
    flattened: Mapping[str, Any],
    candidates: Sequence[str],
    field_name: str,
    *,
    required: bool,
) -> float:
    value = _candidate_value(
        flattened,
        candidates,
        default=None,
        required=required,
        field_name=field_name,
    )

    if value is None:
        return float("nan")

    return _to_float(value, field_name)


def _to_int(value: Any, field_name: str) -> int:
    if isinstance(value, bool):
        raise ValueError(
            f"{field_name} must be an integer, not boolean"
        )

    try:
        numeric = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"{field_name} must be an integer; got {value!r}"
        ) from exc

    if not math.isfinite(numeric) or not numeric.is_integer():
        raise ValueError(
            f"{field_name} must be an integer; got {value!r}"
        )

    return int(numeric)


def _optional_int(
    value: Any,
    field_name: str,
) -> Optional[int]:
    if value is None:
        return None

    return _to_int(value, field_name)


def _normalize_model_name(value: Any) -> str:
    model = _normalize_key(str(value))

    aliases = {
        "copy_persistence": "persistence",
        "copypersistence": "persistence",
        "persistencebaseline": "persistence",
        "persistence_baseline": "persistence",
        "latent_ode": "latentode",
        "independent_latent_ode": "latentode",
        "independentlatentode": "latentode",
        "lg_ode": "lgode",
        "at_ode": "atode",
        "attention_transport_ode": "atode",
        "attentiontransportode": "atode",
    }

    model = aliases.get(model, model)

    if model not in MODEL_ORDER:
        raise ValueError(
            f"Unknown model {value!r}; expected one of {MODEL_ORDER}"
        )

    return model


def _display_model_name(model: str) -> str:
    names = {
        "persistence": "Persistence",
        "latentode": "Latent ODE",
        "lgode": "LG-ODE",
        "atode": "AT-ODE",
    }
    return names.get(model, model)


def _normalize_task_name(value: Any) -> str:
    task = _normalize_key(str(value))

    aliases = {
        "interp": "interpolation",
        "interpolate": "interpolation",
        "extrap": "extrapolation",
        "forecast": "extrapolation",
        "forecasting": "extrapolation",
    }

    task = aliases.get(task, task)

    if task not in TASK_ORDER:
        raise ValueError(
            f"Unknown task {value!r}; expected one of {TASK_ORDER}"
        )

    return task


def _normalize_observed_fraction(value: Any) -> float:
    fraction = _to_float(value, "observed_fraction")

    if fraction in {40.0, 60.0, 80.0}:
        fraction /= 100.0

    for allowed in OBSERVATION_FRACTION_ORDER:
        if math.isclose(
            fraction,
            allowed,
            rel_tol=0.0,
            abs_tol=1e-9,
        ):
            return allowed

    raise ValueError(
        "observed_fraction must be 0.4, 0.6 or 0.8; "
        f"got {fraction}"
    )


def _validate_nonnegative_metric(
    value: float,
    name: str,
    path: Path,
) -> None:
    if math.isfinite(value) and value < 0.0:
        raise ValueError(
            f"{name} cannot be negative in {path}; got {value}"
        )


def _validate_rate(
    value: float,
    name: str,
    path: Path,
) -> None:
    if not math.isfinite(value):
        return

    if value < 0.0 or value > 1.0:
        raise ValueError(
            f"{name} must lie within [0, 1] in {path}; got {value}"
        )


