def _find_json_files(
    input_directory: Path,
    pattern: str,
    output_directory: Path,
) -> List[Path]:
    files = []

    for path in input_directory.glob(pattern):
        if not path.is_file() or path.suffix.lower() != ".json":
            continue

        try:
            path.resolve().relative_to(output_directory.resolve())
            inside_output = True
        except ValueError:
            inside_output = False

        if inside_output and output_directory != input_directory:
            continue

        files.append(path)

    return sorted(files)


def load_results(
    input_directory: Path,
    pattern: str,
    output_directory: Path,
    *,
    strict: bool,
    require_physical_metrics: bool = False,
) -> pd.DataFrame:
    files = _find_json_files(
        input_directory,
        pattern,
        output_directory,
    )

    if not files:
        raise FileNotFoundError(
            f"No JSON files matched {pattern!r} under {input_directory}"
        )

    parsed: List[ParsedResult] = []
    skipped: List[Tuple[Path, str]] = []

    for path in files:
        try:
            parsed.append(
                _parse_result_json(
                    path,
                    input_directory,
                    require_physical_metrics=(
                        require_physical_metrics
                    ),
                )
            )
        except (KeyError, TypeError, ValueError) as exc:
            if strict or require_physical_metrics:
                raise RuntimeError(
                    f"Could not parse result file {path}: {exc}"
                ) from exc

            skipped.append((path, str(exc)))

    for path, reason in skipped:
        warnings.warn(
            f"Skipping non-result or malformed JSON {path}: {reason}",
            stacklevel=2,
        )

    if not parsed:
        raise RuntimeError(
            "No valid power-grid result JSON files were found"
        )

    frame = pd.DataFrame(
        [item.as_dict() for item in parsed]
    )

    frame["task"] = pd.Categorical(
        frame["task"],
        categories=TASK_ORDER,
        ordered=True,
    )
    frame["observed_fraction"] = pd.Categorical(
        frame["observed_fraction"],
        categories=OBSERVATION_FRACTION_ORDER,
        ordered=True,
    )
    frame["model"] = pd.Categorical(
        frame["model"],
        categories=MODEL_ORDER,
        ordered=True,
    )

    frame = frame.sort_values(
        [
            "task",
            "observed_fraction",
            "model",
            "seed",
            "mask_seed",
            "source_file",
        ],
        kind="stable",
    ).reset_index(drop=True)

    frame["task"] = frame["task"].astype(str)
    frame["observed_fraction"] = frame[
        "observed_fraction"
    ].astype(float)
    frame["model"] = frame["model"].astype(str)

    return frame


def _check_duplicate_runs(
    results: pd.DataFrame,
    *,
    allow_duplicates: bool,
) -> None:
    """Detect ambiguous repeated runs."""

    identity = [
        "simbench_code",
        "task",
        "observed_fraction",
        "model",
        "seed",
        "mask_seed",
    ]

    duplicate_mask = results.duplicated(
        identity,
        keep=False,
    )

    if not duplicate_mask.any():
        return

    duplicate_rows = results.loc[
        duplicate_mask,
        identity + ["source_file"],
    ].sort_values(identity)

    message = (
        "Multiple result files have the same experiment identity:\n"
        + duplicate_rows.to_string(index=False)
    )

    if allow_duplicates:
        warnings.warn(
            message
            + "\nDuplicates remain in results.csv and are averaged within "
            "each seed before paired comparisons.",
            stacklevel=2,
        )
    else:
        raise ValueError(
            message
            + "\nRemove duplicate runs or use --allow-duplicates."
        )


def _sample_standard_deviation(
    series: pd.Series,
) -> float:
    values = pd.to_numeric(
        series,
        errors="coerce",
    ).dropna()

    if len(values) < 2:
        return float("nan")

    return float(values.std(ddof=1))


def _finite_mean(
    series: pd.Series,
) -> float:
    values = pd.to_numeric(
        series,
        errors="coerce",
    )
    values = values[np.isfinite(values)]

    if values.empty:
        return float("nan")

    return float(values.mean())


def _nonmissing_count(
    series: pd.Series,
) -> int:
    values = pd.to_numeric(
        series,
        errors="coerce",
    )
    return int(np.isfinite(values).sum())


def _unique_parameter_count(
    series: pd.Series,
) -> Any:
    values = pd.to_numeric(
        series,
        errors="coerce",
    ).dropna().astype(np.int64)

    unique = np.sort(values.unique())

    if unique.size == 0:
        return np.nan

    if unique.size == 1:
        return int(unique[0])

    # Multiple counts normally indicate an accidental architecture mismatch.
    return "|".join(
        str(int(value))
        for value in unique
    )


def _metric_summary(
    group: pd.DataFrame,
    source_column: str,
    output_prefix: str,
) -> Dict[str, Any]:
    return {
        f"mean_{output_prefix}": _finite_mean(
            group[source_column]
        ),
        f"std_{output_prefix}": _sample_standard_deviation(
            group[source_column]
        ),
        f"count_{output_prefix}": _nonmissing_count(
            group[source_column]
        ),
    }


