def _collapse_runs_for_pairing(
    results: pd.DataFrame,
) -> pd.DataFrame:
    """
    Produce one row per paired identity and model.

    Duplicate runs are averaged within each seed before pairing.
    """

    grouping = [
        "simbench_code",
        "task",
        "observed_fraction",
        "seed",
        "mask_seed",
        "model",
    ]

    metric_columns = [
        "normalized_test_mse",
        "normalized_test_mae",
        "voltage_magnitude_mae_pu",
        "voltage_angle_mae_deg",
        "active_power_mae_mw",
        "reactive_power_mae_mvar",
        "ac_active_power_residual_mae_mw",
        "ac_reactive_power_residual_mae_mvar",
        "voltage_violation_rate",
    ]

    aggregations: Dict[str, Tuple[str, str]] = {
        column: (column, "mean")
        for column in metric_columns
    }
    aggregations["duplicate_run_count"] = (
        "source_file",
        "size",
    )

    return (
        results.groupby(
            grouping,
            as_index=False,
            sort=False,
            observed=True,
        )
        .agg(**aggregations)
    )


def _safe_relative_improvement(
    challenger: pd.Series,
    baseline: pd.Series,
) -> pd.Series:
    """
    Compute 100 * (baseline - challenger) / baseline.

    A zero baseline produces NaN rather than an infinite percentage.
    """

    challenger = challenger.astype(float)
    baseline = baseline.astype(float)

    denominator = baseline.where(
        baseline.abs() > 0.0,
        np.nan,
    )

    return 100.0 * (
        baseline - challenger
    ) / denominator


def _paired_metric_statistics(
    paired: pd.DataFrame,
    column_a: str,
    column_b: str,
    output_name: str,
) -> Dict[str, Any]:
    """
    Compute paired absolute and relative improvements for one metric.

    Positive values mean model A has a lower error/residual than model B.
    """

    valid = paired[
        np.isfinite(paired[column_a])
        & np.isfinite(paired[column_b])
    ]

    if valid.empty:
        return {
            f"number_of_{output_name}_pairs": 0,
            f"mean_{output_name}_model_a": np.nan,
            f"mean_{output_name}_model_b": np.nan,
            f"mean_{output_name}_improvement_model_a": np.nan,
            f"std_{output_name}_improvement_model_a": np.nan,
            f"mean_relative_{output_name}_improvement_percent": np.nan,
            f"std_relative_{output_name}_improvement_percent": np.nan,
        }

    improvement = valid[column_b] - valid[column_a]
    relative = _safe_relative_improvement(
        challenger=valid[column_a],
        baseline=valid[column_b],
    )

    return {
        f"number_of_{output_name}_pairs": int(len(valid)),
        f"mean_{output_name}_model_a": float(
            valid[column_a].mean()
        ),
        f"mean_{output_name}_model_b": float(
            valid[column_b].mean()
        ),
        f"mean_{output_name}_improvement_model_a": float(
            improvement.mean()
        ),
        f"std_{output_name}_improvement_model_a": (
            _sample_standard_deviation(improvement)
        ),
        f"mean_relative_{output_name}_improvement_percent": (
            float(relative.mean())
        ),
        f"std_relative_{output_name}_improvement_percent": (
            _sample_standard_deviation(relative)
        ),
    }


def build_paired_comparisons(
    results: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build seed-paired model comparisons.

    Pairing includes grid, task, observed fraction, seed, and mask seed.
    Normalized MSE remains the primary paired comparison. Physical metrics are
    also reported where both paired runs contain them.
    """

    collapsed = _collapse_runs_for_pairing(results)

    pairing_keys = [
        "simbench_code",
        "task",
        "observed_fraction",
        "seed",
        "mask_seed",
    ]

    compared_metrics = [
        "normalized_test_mse",
        "normalized_test_mae",
        "voltage_magnitude_mae_pu",
        "voltage_angle_mae_deg",
        "active_power_mae_mw",
        "reactive_power_mae_mvar",
        "ac_active_power_residual_mae_mw",
        "ac_reactive_power_residual_mae_mvar",
        "voltage_violation_rate",
    ]

    rows: List[Dict[str, Any]] = []

    for group_key, task_fraction_group in collapsed.groupby(
        ["task", "observed_fraction"],
        sort=False,
        observed=True,
    ):
        task, observed_fraction = group_key

        for model_a, model_b, comparison_name in PAIRED_COMPARISONS:
            rename_a = {
                metric: f"{metric}_a"
                for metric in compared_metrics
            }
            rename_b = {
                metric: f"{metric}_b"
                for metric in compared_metrics
            }

            left = task_fraction_group[
                task_fraction_group["model"] == model_a
            ][
                pairing_keys + compared_metrics
            ].rename(columns=rename_a)

            right = task_fraction_group[
                task_fraction_group["model"] == model_b
            ][
                pairing_keys + compared_metrics
            ].rename(columns=rename_b)

            paired = left.merge(
                right,
                on=pairing_keys,
                how="inner",
                validate="one_to_one",
            )

            row: Dict[str, Any] = {
                "task": task,
                "observed_fraction": float(observed_fraction),
                "comparison": comparison_name,
                "model_a": model_a,
                "model_a_display_name": _display_model_name(model_a),
                "model_b": model_b,
                "model_b_display_name": _display_model_name(model_b),
                "number_of_pairs": int(len(paired)),
            }

            if paired.empty:
                for metric in compared_metrics:
                    row.update(
                        _paired_metric_statistics(
                            paired,
                            f"{metric}_a",
                            f"{metric}_b",
                            metric,
                        )
                    )

                row.update(
                    {
                        "median_relative_mse_improvement_percent": np.nan,
                        "win_rate_mse_model_a": np.nan,
                        "tie_rate_mse": np.nan,
                    }
                )
                rows.append(row)
                continue

            for metric in compared_metrics:
                row.update(
                    _paired_metric_statistics(
                        paired,
                        f"{metric}_a",
                        f"{metric}_b",
                        metric,
                    )
                )

            mse_a = paired["normalized_test_mse_a"]
            mse_b = paired["normalized_test_mse_b"]
            valid_mse = np.isfinite(mse_a) & np.isfinite(mse_b)

            if valid_mse.any():
                mse_improvement = (
                    mse_b[valid_mse] - mse_a[valid_mse]
                )
                relative_mse = _safe_relative_improvement(
                    challenger=mse_a[valid_mse],
                    baseline=mse_b[valid_mse],
                )

                tolerance = 1e-12
                wins = mse_improvement > tolerance
                ties = mse_improvement.abs() <= tolerance

                row.update(
                    {
                        "median_relative_mse_improvement_percent": (
                            float(relative_mse.median())
                        ),
                        "win_rate_mse_model_a": float(wins.mean()),
                        "tie_rate_mse": float(ties.mean()),
                    }
                )
            else:
                row.update(
                    {
                        "median_relative_mse_improvement_percent": np.nan,
                        "win_rate_mse_model_a": np.nan,
                        "tie_rate_mse": np.nan,
                    }
                )

            # Backward-compatible names used by existing plotting scripts.
            row["mean_normalized_mse_model_a"] = row[
                "mean_normalized_test_mse_model_a"
            ]
            row["mean_normalized_mse_model_b"] = row[
                "mean_normalized_test_mse_model_b"
            ]
            row["mean_mse_improvement_model_a"] = row[
                "mean_normalized_test_mse_improvement_model_a"
            ]
            row["std_mse_improvement_model_a"] = row[
                "std_normalized_test_mse_improvement_model_a"
            ]
            row["mean_relative_normalized_test_mse_improvement_percent"] = row[
                "mean_relative_normalized_test_mse_improvement_percent"
            ]
            row["std_relative_mse_improvement_percent"] = row[
                "std_relative_normalized_test_mse_improvement_percent"
            ]

            row["mean_normalized_mae_model_a"] = row[
                "mean_normalized_test_mae_model_a"
            ]
            row["mean_normalized_mae_model_b"] = row[
                "mean_normalized_test_mae_model_b"
            ]
            row["mean_mae_improvement_model_a"] = row[
                "mean_normalized_test_mae_improvement_model_a"
            ]
            row["std_mae_improvement_model_a"] = row[
                "std_normalized_test_mae_improvement_model_a"
            ]
            row["mean_relative_mae_improvement_percent"] = row[
                "mean_relative_normalized_test_mae_improvement_percent"
            ]

            rows.append(row)

    paired_comparisons = pd.DataFrame(rows)

    comparison_order = [
        name
        for _, _, name in PAIRED_COMPARISONS
    ]

    paired_comparisons["task"] = pd.Categorical(
        paired_comparisons["task"],
        categories=TASK_ORDER,
        ordered=True,
    )
    paired_comparisons["observed_fraction"] = pd.Categorical(
        paired_comparisons["observed_fraction"],
        categories=OBSERVATION_FRACTION_ORDER,
        ordered=True,
    )
    paired_comparisons["comparison"] = pd.Categorical(
        paired_comparisons["comparison"],
        categories=comparison_order,
        ordered=True,
    )

    paired_comparisons = paired_comparisons.sort_values(
        [
            "task",
            "observed_fraction",
            "comparison",
        ],
        kind="stable",
    ).reset_index(drop=True)

    paired_comparisons["task"] = paired_comparisons[
        "task"
    ].astype(str)
    paired_comparisons["observed_fraction"] = paired_comparisons[
        "observed_fraction"
    ].astype(float)
    paired_comparisons["comparison"] = paired_comparisons[
        "comparison"
    ].astype(str)

    return paired_comparisons


def _atomic_write_csv(
    frame: pd.DataFrame,
    path: Path,
) -> None:
    """Write a CSV atomically."""

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    file_descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=str(path.parent),
    )
    os.close(file_descriptor)

    temporary_path = Path(temporary_name)

    try:
        frame.to_csv(
            temporary_path,
            index=False,
            float_format="%.10g",
        )
        os.replace(
            temporary_path,
            path,
        )
    except Exception:
        temporary_path.unlink(missing_ok=True)
        raise


def _warn_missing_physical_metrics(
    results: pd.DataFrame,
) -> None:
    missing_messages = []

    for column in PHYSICAL_METRIC_COLUMNS:
        missing_count = int(
            pd.to_numeric(
                results[column],
                errors="coerce",
            ).isna().sum()
        )

        if missing_count:
            missing_messages.append(
                f"{column}: {missing_count}/{len(results)} missing"
            )

    if missing_messages:
        warnings.warn(
            "Some result files do not contain all physical reporting "
            "metrics. Missing entries are written as NaN:\n  "
            + "\n  ".join(missing_messages)
            + "\nUse --require-physical-metrics for final paper tables.",
            stacklevel=2,
        )


def _format_metric(
    value: Any,
    *,
    percentage: bool = False,
) -> str:
    if pd.isna(value):
        return "NA"

    numeric = float(value)

    if percentage:
        return f"{100.0 * numeric:.3f}%"

    return f"{numeric:.6g}"


def _print_report(
    results: pd.DataFrame,
    summary: pd.DataFrame,
    paired: pd.DataFrame,
    output_directory: Path,
) -> None:
    number_of_files = len(results)
    number_of_seeds = results["seed"].nunique()

    print(
        f"Aggregated {number_of_files} result files "
        f"across {number_of_seeds} unique seeds."
    )
    print(f"Wrote: {output_directory / 'results.csv'}")
    print(f"Wrote: {output_directory / 'summary.csv'}")
    print(
        f"Wrote: {output_directory / 'paired_comparisons.csv'}"
    )

    transport = paired[
        paired["comparison"] == "AT-ODE versus LG-ODE"
    ]

    if not transport.empty:
        print("\nAT-ODE transport improvement over LG-ODE:")

        for row in transport.itertuples(index=False):
            value = row.mean_relative_normalized_test_mse_improvement_percent
            pairs = row.number_of_pairs

            if pd.isna(value):
                text = "not available"
            else:
                text = f"{value:.3f}%"

            print(
                f"  {row.task}, "
                f"{100.0 * row.observed_fraction:.0f}% observed: "
                f"{text} ({pairs} paired seeds)"
            )

    print("\nPaper metric summary:")

    printable_columns = [
        "task",
        "observed_fraction",
        "model_display_name",
        "number_of_seeds",
        "mean_normalized_mse",
        "mean_voltage_magnitude_mae_pu",
        "mean_voltage_angle_mae_deg",
        "mean_active_power_mae_mw",
        "mean_reactive_power_mae_mvar",
        "mean_ac_active_power_residual_mae_mw",
        "mean_ac_reactive_power_residual_mae_mvar",
        "mean_voltage_violation_rate",
        "mean_training_time_seconds",
        "parameter_count",
    ]

    print(
        summary[printable_columns].to_string(
            index=False,
            na_rep="NA",
        )
    )


def parse_args(
    argv: Optional[Sequence[str]] = None,
) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Aggregate SimBench LG-ODE result JSON files into results.csv, "
            "summary.csv and paired_comparisons.csv, including physical-unit "
            "and AC-consistency metrics."
        )
    )

    parser.add_argument(
        "--input-dir",
        type=Path,
        required=True,
        help="Directory containing experiment result JSON files.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help=(
            "Directory for output CSV files. Defaults to --input-dir."
        ),
    )
    parser.add_argument(
        "--pattern",
        type=str,
        default="**/*.json",
        help=(
            "Glob pattern relative to --input-dir. "
            "Default: **/*.json"
        ),
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help=(
            "Fail on every malformed or unrelated JSON file instead of "
            "warning and skipping it."
        ),
    )
    parser.add_argument(
        "--require-physical-metrics",
        action="store_true",
        help=(
            "Require voltage, power, AC-residual, and voltage-violation "
            "metrics in every result JSON. Recommended for final paper "
            "tables."
        ),
    )
    parser.add_argument(
        "--allow-duplicates",
        action="store_true",
        help=(
            "Allow repeated grid/task/fraction/model/seed/mask-seed runs. "
            "They remain in results.csv and are averaged within each seed "
            "for paired comparisons."
        ),
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Do not print the terminal summary.",
    )

    return parser.parse_args(argv)


def main(
    argv: Optional[Sequence[str]] = None,
) -> int:
    args = parse_args(argv)

    input_directory = args.input_dir.expanduser().resolve()
    output_directory = (
        args.output_dir.expanduser().resolve()
        if args.output_dir is not None
        else input_directory
    )

    if not input_directory.is_dir():
        raise NotADirectoryError(
            f"Input directory does not exist: {input_directory}"
        )

    results = load_results(
        input_directory=input_directory,
        pattern=args.pattern,
        output_directory=output_directory,
        strict=args.strict,
        require_physical_metrics=args.require_physical_metrics,
    )

    _check_duplicate_runs(
        results,
        allow_duplicates=args.allow_duplicates,
    )

    if not args.require_physical_metrics:
        _warn_missing_physical_metrics(results)

    summary = build_summary(results)
    paired_comparisons = build_paired_comparisons(results)

    _atomic_write_csv(
        results,
        output_directory / "results.csv",
    )
    _atomic_write_csv(
        summary,
        output_directory / "summary.csv",
    )
    _atomic_write_csv(
        paired_comparisons,
        output_directory / "paired_comparisons.csv",
    )

    if not args.quiet:
        _print_report(
            results,
            summary,
            paired_comparisons,
            output_directory,
        )

    return 0


